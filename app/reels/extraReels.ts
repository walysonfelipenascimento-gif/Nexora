export function imageForCaption(caption: string) {
  const t = caption.toLowerCase();
  if (/professor|prova|mat[eé]ria|escola|trabalho|estudar|grupo|aula/.test(t)) return imageMap.school;
  if (/comida|comer|lanche|bolo|salada|cozinha|receita|sobremesa|pizza|geladeira|hamb[uú]rguer/.test(t)) return imageMap.food;
  if (/dormir|sono|soneca|acordar|alarme|cama|despertador/.test(t)) return imageMap.sleep;
  if (/celular|mensagem|wifi|wi-fi|internet|notifica[cç][aã]o|senha|câmera|áudio|audio/.test(t)) return imageMap.phone;
  if (/dinheiro|banco|pagamento|conta|promo[cç][aã]o|pre[cç]o|economizar|entrega/.test(t)) return imageMap.money;
  if (/casa|m[aã]e|arm[aá]rio|roupa|cabelo|quarto|carregador/.test(t)) return imageMap.home;
  if (/amigo|amiga|grupo|visita|festa|pessoa|fofoca|conversa/.test(t)) return imageMap.friends;
  if (/viagem|ônibus|onibus|chuva|guarda-chuva|lugar|f[eé]rias/.test(t)) return imageMap.travel;
  return imageMap.general;
}

